#!/usr/bin/env python3
"""W5.T0: bucket every token of each agent run by role, per arm, passing and failing runs apart.

  python3 -I w5t0_attrib.py TRANSCRIPT_DIR ROWS_DIR OUT_PREFIX [--drop-bucket NAME]
TRANSCRIPT_DIR holds <arm>_<task>_r<run>.jsonl (claude -p stream-json); ROWS_DIR holds <arm>.tsv (the harness rows, the
independent source of the per-run totals). --drop-bucket is the red mutant: it deletes one bucket before the sum check.

Two metrics, both decomposed EXACTLY (buckets sum to the run total by construction, then are checked against the rows):
  in+out  = input_tokens + output_tokens (the "727 vs 517" metric). input_tokens is the UNCACHED input only (a few per
            run); cache reads/creates are not in it. Buckets: uncached_input, out_thinking, out_toolargs, out_text.
  total   = in+out + cache_read + cache_create. Every API call re-reads the whole context, so a token that enters the
            context after call i is billed on every later call. Buckets: prefix (context of call 1 = system + tool
            definitions + task prompt, billed once per call), assistant_reread (earlier model output re-read),
            results:<tool> (earlier tool results re-read, by tool name), plus the in+out buckets.
Method: per API call (stream blocks merged by message id) ctx_j = input + cache_read + cache_create; sum_j ctx_j telescopes
into N*ctx_1 + sum_i (N-i)*(ctx_{i+1}-ctx_i). The growth d_i = ctx_{i+1}-ctx_i is split into assistant tokens (the run's
output tokens apportioned over calls by generated bytes, capped at d_i) and the remainder to that call's tool results by
result bytes. Output tokens: thinking = usage.output_tokens_details.thinking_tokens; the rest is split between tool-call
args and text by bytes. Per-call stream output_tokens are start snapshots and are NOT used."""
import csv, collections, json, os, sys

args = [a for a in sys.argv[1:] if not a.startswith("--")]
drop = sys.argv[sys.argv.index("--drop-bucket") + 1] if "--drop-bucket" in sys.argv else None
if drop:
    args.remove(drop)
tdir, rdir, out = args
PIN = os.environ.get("MANUK_CHROME_PIN", "145.0.7632.116")


def blen(x):
    return len(json.dumps(x, ensure_ascii=False).encode())


def attribute(path):
    calls, order, names, result_of = {}, [], {}, collections.defaultdict(list)
    final = None
    for line in open(path):
        d = json.loads(line)
        if d["type"] == "assistant":
            m = d["message"]
            c = calls.get(m["id"])
            if c is None:
                u = m["usage"]
                c = calls[m["id"]] = dict(ctx=u["input_tokens"] + u["cache_read_input_tokens"] + u["cache_creation_input_tokens"],
                                          w_args=0, w_text=0, w_think=0)
                order.append(m["id"])
            for b in m["content"]:
                if b["type"] == "tool_use":
                    names[b["id"]] = (m["id"], b["name"]); c["w_args"] += blen(b["input"])
                elif b["type"] == "text":
                    c["w_text"] += len(b["text"].encode())
                elif b["type"] == "thinking":
                    c["w_think"] += len(b.get("thinking", "").encode())
        elif d["type"] == "user":
            for b in d["message"]["content"]:
                if b.get("type") == "tool_result" and b["tool_use_id"] in names:
                    cid, nm = names[b["tool_use_id"]]
                    result_of[cid].append((nm, blen(b.get("content"))))
        elif d["type"] == "result":
            final = d["usage"]
    u = final
    think = u.get("output_tokens_details", {}).get("thinking_tokens", 0)
    o = u["output_tokens"]
    wa = sum(c["w_args"] for c in calls.values()); wt = sum(c["w_text"] for c in calls.values())
    rest = o - think
    args_tok = rest * wa / (wa + wt) if wa + wt else 0.0
    b = collections.Counter(uncached_input=u["input_tokens"], out_thinking=think, out_toolargs=args_tok, out_text=rest - args_tok)
    inout = u["input_tokens"] + o
    # exact total from the calls; checked against the result line by the caller
    ctxs = [calls[i]["ctx"] for i in order]
    n = len(ctxs)
    wsum = sum(calls[i]["w_args"] + calls[i]["w_text"] + calls[i]["w_think"] + 1 for i in order)
    b["prefix"] += n * ctxs[0]
    for i in range(n - 1):
        c = calls[order[i]]
        d = ctxs[i + 1] - ctxs[i]
        asst = min(max(d, 0), o * (c["w_args"] + c["w_text"] + c["w_think"] + 1) / wsum)
        res = d - asst
        reread = n - 1 - i
        b["assistant_reread"] += asst * reread
        rs = result_of.get(order[i], [])
        tb = sum(x[1] for x in rs)
        if rs and tb:
            for nm, by in rs:
                b["results:" + nm] += res * reread * by / tb
        else:
            b["results:(none)"] += res * reread
    cache_in = u["cache_read_input_tokens"] + u["cache_creation_input_tokens"]
    total = inout + cache_in
    if drop:
        for k in list(b):
            if k == drop or (drop == "results" and k.startswith("results:")):
                del b[k]
    return b, inout, total, n


rows = {}
for arm in sorted(f[:-4] for f in os.listdir(rdir) if f.endswith(".tsv") and not f.endswith(".turns.tsv")):
    for r in csv.DictReader(open(f"{rdir}/{arm}.tsv"), delimiter="\t"):
        rows[(arm.replace('playwright_preload', 'playwright+preload'), r["task"], r["run"])] = r
bad = n_runs = 0
agg = collections.defaultdict(lambda: collections.defaultdict(float))  # (arm,outcome) -> bucket -> sum
cnt = collections.Counter()
for (arm, task, run), r in sorted(rows.items()):
    if r["chrome_ver"] != PIN:
        print(f"RED wrong chrome_ver {r['chrome_ver']} on {arm} {task} r{run}"); bad += 1; continue
    fn = f"{tdir}/{arm.replace('playwright_preload', 'playwright+preload')}_{task}_r{run}.jsonl"
    if not os.path.exists(fn):
        print(f"RED missing transcript {fn}"); bad += 1; continue
    b, inout, total, n = attribute(fn)
    want_io = int(r["input_tokens"]) + int(r["output_tokens"])
    want_tot = want_io + int(r["cache_read_tokens"]) + int(r["cache_create_tokens"])
    keys_io = ("uncached_input", "out_thinking", "out_toolargs", "out_text")
    s_io = sum(b[k] for k in keys_io)
    s_tot = s_io + sum(v for k, v in b.items() if k not in keys_io)
    ok = abs(s_io - want_io) <= 0.01 * want_io and abs(s_tot - want_tot) <= 0.01 * want_tot
    n_runs += 1
    if not ok:
        bad += 1; print(f"RED {arm} {task} r{run}: in+out buckets {s_io:.0f} vs row {want_io}; total buckets {s_tot:.0f} vs row {want_tot}")
    oc = "pass" if r["pass"] == "1" else "fail"
    cnt[(arm, oc)] += 1
    for k, v in b.items():
        agg[(arm, oc)][k] += v
IO = ("uncached_input", "out_thinking", "out_toolargs", "out_text")
with open(out + ".tsv", "w") as f:
    f.write("chrome_ver\tarm\toutcome\truns\tmetric\tbucket\ttokens_per_run\n")
    for (arm, oc), bk in sorted(agg.items()):
        n = cnt[(arm, oc)]
        for k, v in sorted(bk.items(), key=lambda kv: -kv[1]):
            f.write(f"{PIN}\t{arm}\t{oc}\t{n}\t{'in+out' if k in IO else 'total_extra'}\t{k}\t{v / n:.1f}\n")
print(f"{n_runs} runs checked, {bad} RED (buckets must sum to the row total within 1%)" + (f"  [mutant: dropped {drop}]" if drop else ""))
sys.exit(1 if bad else 0)
