#!/usr/bin/env python3
"""W4.B4.a: (1) check per-turn output_tokens sum to each row's output_tokens (<=1%); (2) per-tool attribution table.

  python3 -I b4a_attrib.py DIR [--drop-last]     (DIR holds <arm>.tsv + <arm>.tsv.turns.tsv; --drop-last is the red mutant)
Output tokens per turn are the run total apportioned by generated bytes (run_arm.turn_log); result_bytes is the tool
observation size in bytes (not tokens)."""
import csv, collections, os, sys

d = sys.argv[1]; drop = "--drop-last" in sys.argv
bad = 0; table = {}
for arm in sorted(f[:-4] for f in os.listdir(d) if f.endswith(".tsv") and not f.endswith(".turns.tsv")):
    rows = list(csv.DictReader(open(f"{d}/{arm}.tsv"), delimiter="\t"))
    turns = list(csv.DictReader(open(f"{d}/{arm}.tsv.turns.tsv"), delimiter="\t"))
    by = collections.defaultdict(list)
    for t in turns:
        by[(t["task"], t["run"])].append(t)
    agg = collections.defaultdict(lambda: [0, 0, 0])
    for r in rows:
        ts = by[(r["task"], r["run"])]
        if drop and ts:
            ts = ts[:-1]
        s, tot = sum(int(t["output_tokens"]) for t in ts), int(r["output_tokens"])
        ok = abs(s - tot) <= 0.01 * tot
        bad += not ok
        print(f"{arm} {r['task']} turns={len(ts)} sum={s} row={tot} {'ok' if ok else 'RED'}")
        for t in ts:
            a = agg[t["tool"] or "(final answer)"]; a[0] += 1; a[1] += int(t["output_tokens"]); a[2] += int(t["result_bytes"])
    table[arm] = (agg, len(rows))
print("\nchrome_ver=" + (rows[0]["chrome_ver"] if rows else "?"))
for arm, (agg, n) in table.items():
    print(f"\n{arm} ({n} rows)  tool | calls/task | out_tok/task | result_bytes/task")
    for k, (c, o, b) in sorted(agg.items(), key=lambda kv: -kv[1][1]):
        print(f"  {k} | {c/n:.2f} | {o/n:.1f} | {b/n:.0f}")
    print(f"  TOTAL | {sum(v[0] for v in agg.values())/n:.2f} | {sum(v[1] for v in agg.values())/n:.1f} | {sum(v[2] for v in agg.values())/n:.0f}")
sys.exit(1 if bad else 0)
