#!/usr/bin/env python3
"""RG.S1.c.a.a: networkin-3 noise table over every existing manuk rows file.

  python3 -I docs/sprint/rg/S1c-noise.py            # rewrite docs/sprint/rg/S1c-noise.md
  python3 -I docs/sprint/rg/S1c-noise.py --check    # exit 1 if the committed table is stale
  python3 -I docs/sprint/rg/S1c-noise.py --check --root DIR   # mutation test on a copy

Reads docs/sprint/rg/*real-manuk.tsv (or DIR/*real-manuk.tsv), keeps task networkin-3, and
counts from the recorded columns only. No runs are made. The table is generated in full, so
any hand-edited row that changes a count makes --check exit 1.

Columns used: pass, evals_ok, evals_n, run, chrome_ver, arm.
Publish proxy: evals_ok >= 1. Calibrated against the hand labels in S1c-classify.md (S1c r1, r2
and E1a r3, R3a r2 are labelled unpublished and have evals_ok 0; S1c r3 and S1ca r1-r3 are labelled
published and have evals_ok >= 2). With a post present, the 'post added' eval passes, so
evals_ok 0 means no post was added.

Per-eval split: the rows store only a count. Where a transcript with the typed post text is
committed (E2c-ahead-transcripts), the 'event' and 'network' substrings are read from the typed
text. Elsewhere the split is not recoverable and is reported as unresolved.
"""
import argparse
import csv
import glob
import json
import os
import sys

TASK = 'networkin-3'
HERE = os.path.dirname(os.path.abspath(__file__))
# rows file basename -> transcript directory (relative to the rows root) holding typed text per run
TRANSCRIPTS = {'E2c-ahead-real-manuk.tsv': 'E2c-ahead-transcripts'}
OUT = os.path.join(HERE, 'S1c-noise.md')


def typed_text(path):
    """Concatenate the text of every browser type call in a transcript; None if no file."""
    if not os.path.exists(path):
        return None
    parts = []
    for line in open(path, encoding='utf-8'):
        try:
            d = json.loads(line)
        except ValueError:
            continue
        for c in (d.get('message', {}).get('content') or []):
            if isinstance(c, dict) and c.get('type') == 'tool_use' and c.get('name', '').endswith('__type'):
                parts.append(c.get('input', {}).get('text', ''))
    return '\n'.join(parts)


def contains(text, word):
    return word in text or word.capitalize() in text


def collect(root):
    files = sorted(glob.glob(os.path.join(root, '*real-manuk.tsv')))
    per_file = []
    for f in files:
        base = os.path.basename(f)
        rows = [r for r in csv.DictReader(open(f, encoding='utf-8'), delimiter='\t') if r['task'] == TASK]
        if not rows:
            continue
        tdir = os.path.join(root, TRANSCRIPTS[base]) if base in TRANSCRIPTS else None
        st = {'file': base, 'rows': len(rows), 'pass': 0, 'pub': 0,
              'ok': {0: 0, 1: 0, 2: 0, 3: 0}, 'resolved': 0, 'event_miss': 0, 'network_miss': 0,
              'chrome': sorted({r['chrome_ver'] for r in rows}), 'arm': sorted({r['arm'] for r in rows}),
              'bad_pass': 0}
        for r in rows:
            ok = int(r['evals_ok'])
            st['ok'][ok] += 1
            st['pass'] += r['pass'] == '1'
            st['pub'] += ok >= 1
            if r['pass'] == '1' and ok != 3:
                st['bad_pass'] += 1
            if tdir:
                text = typed_text(os.path.join(tdir, 'manuk_%s_r%s.jsonl' % (TASK, r['run'])))
                if text is not None:
                    st['resolved'] += 1
                    st['event_miss'] += not contains(text, 'event')
                    st['network_miss'] += not contains(text, 'network')
        per_file.append(st)
    return per_file


def pct(a, b):
    return '-' if b == 0 else '%d%%' % round(100.0 * a / b)


def render(root):
    per_file = collect(root)
    tot = {k: 0 for k in ('rows', 'pass', 'pub', 'resolved', 'event_miss', 'network_miss', 'bad_pass')}
    tot_ok = {0: 0, 1: 0, 2: 0, 3: 0}
    for s in per_file:
        for k in tot:
            tot[k] += s[k]
        for k in tot_ok:
            tot_ok[k] += s['ok'][k]
    out = []
    out.append('# RG.S1.c.a.a: networkin-3 noise across all manuk rows files')
    out.append('')
    out.append('Generated by `docs/sprint/rg/S1c-noise.py` from `docs/sprint/rg/*real-manuk.tsv`. No runs.')
    chromes = sorted({c for s in per_file for c in s['chrome']})
    arms = sorted({a for s in per_file for a in s['arm']})
    out.append('')
    out.append('chrome_ver=%s; arm=%s; task=%s; judge: none (three deterministic jmespath evals).' %
               (', '.join(chromes), ', '.join(arms), TASK))
    out.append('')
    out.append('Definitions (see the script docstring for the calibration):')
    out.append('- `pass`: the row\'s recorded pass flag (all three evals).')
    out.append('- `published*`: evals_ok >= 1, i.e. a post was added (proxy).')
    out.append('- `ok=0..3`: rows with that many of the three evals passing.')
    out.append('- `event miss` / `network miss`: counted only in rows whose typed text is committed; `resolved` is that row count.')
    out.append('')
    out.append('| rows file | runs | pass | published* | ok=0 | ok=1 | ok=2 | ok=3 | resolved | event miss | network miss |')
    out.append('|---|---|---|---|---|---|---|---|---|---|---|')
    for s in per_file:
        out.append('| %s | %d | %d/%d (%s) | %d/%d (%s) | %d | %d | %d | %d | %d | %d | %d |' % (
            s['file'], s['rows'], s['pass'], s['rows'], pct(s['pass'], s['rows']),
            s['pub'], s['rows'], pct(s['pub'], s['rows']),
            s['ok'][0], s['ok'][1], s['ok'][2], s['ok'][3],
            s['resolved'], s['event_miss'], s['network_miss']))
    out.append('| **all** | %d | %d/%d (%s) | %d/%d (%s) | %d | %d | %d | %d | %d | %d | %d |' % (
        tot['rows'], tot['pass'], tot['rows'], pct(tot['pass'], tot['rows']),
        tot['pub'], tot['rows'], pct(tot['pub'], tot['rows']),
        tot_ok[0], tot_ok[1], tot_ok[2], tot_ok[3],
        tot['resolved'], tot['event_miss'], tot['network_miss']))
    out.append('')
    out.append('Checks on the recorded columns:')
    out.append('- rows with pass=1 and evals_ok != 3: %d' % tot['bad_pass'])
    out.append('- rows with evals_ok=2 and published*: %d (one substring eval missed; which one is unresolved unless transcript-resolved)' %
               (tot_ok[2]))
    out.append('- rows with evals_ok=1 (both substring evals missed, post present): %d' % tot_ok[1])
    out.append('')
    out.append('Not claimed: per-eval counts for rows without a committed transcript. The S1c-classify.md labels for S1c and S1ca came from transcripts that are not committed here, so they are not re-derived.')
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--root', default=HERE)
    a = ap.parse_args()
    text = render(a.root)
    if a.check:
        committed = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if text != committed:
            sys.stderr.write('S1c-noise.md is stale: a rows file changed a networkin-3 count\n')
            sys.stdout.write(text)
            return 1
        print('GREEN: S1c-noise.md matches the rows files')
        return 0
    open(OUT, 'w', encoding='utf-8').write(text)
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
